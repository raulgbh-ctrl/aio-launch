"""Write cornerplay/toastsi18n.py: every message app.py shows as a toast, as a template
("Could not start %1: %2") Qt's lupdate can find, so toasts can be translated in one place.
Run after adding or changing toasts:  python3 tools/toast_templates.py"""
import ast
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
tree = ast.parse((ROOT / "cornerplay/app.py").read_text())
tpls = set()
for node in ast.walk(tree):
    if isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute) and node.func.attr == "emit":
        tgt = node.func.value
        name = tgt.attr if isinstance(tgt, ast.Attribute) else getattr(tgt, "id", "")
        if name not in ("toast", "_worker_toast") or not node.args:
            continue
        for a in [node.args[0]] + ([node.args[0].body, node.args[0].orelse] if isinstance(node.args[0], ast.IfExp) else []):
            if isinstance(a, ast.Constant) and isinstance(a.value, str):
                tpls.add(a.value)
            elif isinstance(a, ast.JoinedStr):
                out, n = "", 0
                for v in a.values:
                    if isinstance(v, ast.Constant):
                        out += v.value
                    else:
                        n += 1
                        out += f"%{n}"
                tpls.add(out)
tpls = sorted(t for t in tpls if re.search(r"[A-Za-z]{3}", t))
lines = ['"""Toasts in the interface language (generated by tools/toast_templates.py: do not edit by hand).',
         "",
         "app.py builds its messages in English; translate() finds the template a message came from",
         '("Could not start %1: %2"), translates it, and puts the same parts back in."""',
         "import re",
         "",
         "from PySide6.QtCore import QCoreApplication",
         "",
         "TEMPLATES = ["] + [f"    {t!r}," for t in tpls] + ["]", "", "",
         "def _names():",
         '    """Never called: lists the templates for lupdate."""',
         "    return (" + ",\n            ".join(f'QCoreApplication.translate("toast", {t!r})' for t in tpls) + ")",
         "", "",
         "_compiled = None", "", "",
         "def _patterns():",
         "    global _compiled",
         "    if _compiled is None:",
         "        out = []",
         "        for t in sorted(TEMPLATES, key=lambda x: -len(re.sub(r'%\\d', '', x))):",
         "            if '%' not in t:",
         "                continue",
         "            rx = '^' + re.sub(r'%(\\d)', lambda m: f'(?P<g{m.group(1)}>.+?)', re.escape(t).replace('%', '%')) + '$'",
         "            out.append((t, re.compile(rx, re.S)))",
         "        _compiled = out",
         "    return _compiled",
         "", "",
         "def translate(message):",
         '    """message in the interface language when it is one of the templates, else as it is."""',
         '    whole = QCoreApplication.translate("toast", message)',
         "    if whole != message:",
         "        return whole",
         "    for t, rx in _patterns():",
         "        m = rx.match(message)",
         "        if m:",
         '            out = QCoreApplication.translate("toast", t)',
         "            if out == t:",
         "                return message",
         "            for k, v in m.groupdict().items():",
         "                out = out.replace('%' + k[1:], v)",
         "            return out",
         "    return message",
         ""]
(ROOT / "cornerplay/toastsi18n.py").write_text("\n".join(lines))
print(len(tpls), "templates")
